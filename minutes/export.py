"""Writing a meeting folder: names, transcript formats, summary markdown."""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import time
import uuid
from pathlib import Path

from .summarize import fmt_time

APP_MARKER = "minutes"
_ILLEGAL = re.compile(r'[<>:"/\\|?*\x00-\x1f]')


# Windows device names: reserved even with an extension ("CON.srt"), and a folder with
# one of these names can't be opened or deleted from Explorer.
_RESERVED = {"CON", "PRN", "AUX", "NUL", *(f"COM{i}" for i in range(1, 10)), *(f"LPT{i}" for i in range(1, 10))}


def clean_name(name: str) -> str:
    name = _ILLEGAL.sub("", name)
    name = re.sub(r"\s+", " ", name)[:100].strip().strip(".").strip()
    if name.split(".")[0].upper() in _RESERVED:
        name += "_"
    return name or "Meeting"


def slug_title(title: str) -> str:
    words = re.findall(r"[A-Za-z0-9][A-Za-z0-9'&+]*", title)
    return "-".join(w if w.isupper() else w[:1].upper() + w[1:] for w in words[:8])


def default_name(meeting_date: str, title: str, fallback: str) -> str:
    return clean_name(f"{meeting_date}_{slug_title(title) or fallback}")


def file_names(name: str) -> dict[str, str]:
    return {
        "transcript": f"{name}_transcript.txt",
        "srt": f"{name}.srt",
        "summary": f"{name}_summary.md",
        "json": f"{name}.json",
        "wav": f"{name}_audio.wav",
    }


def speaker_name(meeting: dict, label: str | None) -> str | None:
    if not label:
        return None
    return (meeting.get("speakers") or {}).get(label) or label


def replace_names(value, mapping: dict[str, str]):
    """Rename speakers inside summary text (whole-word, longest names first)."""
    if not mapping:
        return value
    if isinstance(value, str):
        for old in sorted(mapping, key=len, reverse=True):
            value = re.sub(rf"(?<!\w){re.escape(old)}(?!\w)", lambda _m, o=old: mapping[o], value)
        return value
    if isinstance(value, list):
        return [replace_names(v, mapping) for v in value]
    if isinstance(value, dict):
        return {k: (v if k == "start" else replace_names(v, mapping)) for k, v in value.items()}
    return value


# ---------------------------------------------------------------- renderers


def render_txt(meeting: dict) -> str:
    out = [meeting["name"], ""]
    last = object()
    for seg in meeting["segments"]:
        who = speaker_name(meeting, seg.get("speaker"))
        if who != last:
            if out[-1] != "":
                out.append("")
            out.append(f"[{fmt_time(seg['start'])}] {who}:" if who else f"[{fmt_time(seg['start'])}]")
            last = who
        out.append(seg["text"])
    return "\n".join(out).rstrip() + "\n"


def _srt_time(t: float) -> str:
    ms = int(round(t * 1000))
    h, ms = divmod(ms, 3_600_000)
    m, ms = divmod(ms, 60_000)
    s, ms = divmod(ms, 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"


def render_srt(meeting: dict) -> str:
    blocks = []
    for i, seg in enumerate(meeting["segments"], 1):
        who = speaker_name(meeting, seg.get("speaker"))
        text = f"{who}: {seg['text']}" if who else seg["text"]
        blocks.append(f"{i}\n{_srt_time(seg['start'])} --> {_srt_time(seg['end'])}\n{text}\n")
    return "\n".join(blocks)


def render_summary_md(meeting: dict) -> str:
    s = meeting.get("summary")
    lines = [f"# {s.get('title') if s and s.get('title') else meeting['name']}", ""]
    meta = [f"**Date:** {meeting['meeting_date']}", f"**Length:** {fmt_time(meeting['duration'])}"]
    names = sorted({speaker_name(meeting, seg.get("speaker")) for seg in meeting["segments"]} - {None})
    if names:
        meta.append(f"**Speakers:** {', '.join(names)}")
    lines += ["  \n".join(meta), ""]
    if not s:
        lines.append("_No summary was generated._")
        return "\n".join(lines) + "\n"
    if s["overview"]:
        lines += ["## Overview", "", s["overview"], ""]
    if s["decisions"]:
        lines += ["## Decisions", ""] + [f"- {d}" for d in s["decisions"]] + [""]
    if s["action_items"]:
        lines += ["## Action items", ""]
        for a in s["action_items"]:
            extra = " — ".join(x for x in (a["owner"] and f"**{a['owner']}**", a["due"] and f"due {a['due']}") if x)
            lines.append(f"- [ ] {a['task']}" + (f" ({extra})" if extra else ""))
        lines.append("")
    if s["open_questions"]:
        lines += ["## Open questions", ""] + [f"- {q}" for q in s["open_questions"]] + [""]
    if s["topics"]:
        lines += ["## Topics", ""] + [f"- `{fmt_time(t['start'])}` {t['topic']}" for t in s["topics"]] + [""]
    engine = meeting.get("summary_engine")
    if engine:
        lines += [f"<sub>Summary by {engine}. Generated by Minutes.</sub>", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------- writing


def write_atomic(path: Path, text: str) -> None:
    """Write via a temp file + rename, so a crash or full disk leaves either the old
    file or the new one, never a half-written one."""
    tmp = path.with_name(f"{path.name}.tmp-{uuid.uuid4().hex[:8]}")
    try:
        tmp.write_text(text, encoding="utf-8")
        _replace(tmp, path)
    except BaseException:
        tmp.unlink(missing_ok=True)
        raise


def _replace(src: Path, dst: Path, attempts: int = 50) -> None:
    # Windows refuses to replace a file another process has open (e.g. a second copy
    # of the app reading settings.json at that instant); readers finish in
    # milliseconds, so retry briefly.
    for i in range(attempts):
        try:
            os.replace(src, dst)
            return
        except PermissionError:
            if i == attempts - 1:
                raise
            time.sleep(0.02)


def _same_name(a: str, b: str) -> bool:
    # Windows (and default macOS) file systems are case-insensitive: "Notes" and "notes"
    # are the same file. Comparing case-insensitively everywhere is the safe direction:
    # at worst a stale file is kept, never a just-written one deleted.
    return a.casefold() == b.casefold()


def _same_path(a: Path, b: Path) -> bool:
    try:
        return a.exists() and b.exists() and os.path.samefile(a, b)
    except OSError:
        return False


def _rename(src: Path, dst: Path) -> None:
    """Rename, including case-only changes (which need a hop through a temp name)."""
    if src.name == dst.name and src.parent == dst.parent:
        return
    if _same_name(str(src), str(dst)):
        tmp = src.with_name(f"{src.name}.renaming-{uuid.uuid4().hex[:8]}")
        src.rename(tmp)
        tmp.rename(dst)
    else:
        src.rename(dst)


def unique_folder(base: Path, name: str, current: Path | None = None) -> Path:
    candidate = base / name
    n = 2
    while candidate.exists() and not (current is not None and _same_path(candidate, current)):
        candidate = base / f"{name} ({n})"
        n += 1
    return candidate


def _kind(filename: str) -> str | None:
    for kind, suffix in (("transcript", "_transcript.txt"), ("summary", "_summary.md"),
                         ("wav", "_audio.wav"), ("srt", ".srt"), ("json", ".json")):
        if filename.endswith(suffix):
            return kind
    return None


def write_meeting(meeting: dict, output_dir: Path, wav_source: Path | None = None) -> dict:
    """Write (or rewrite after a rename) every file for a meeting. Returns the meeting
    with updated folder/name/files."""
    output_dir.mkdir(parents=True, exist_ok=True)
    old_folder = Path(meeting["folder"]) if meeting.get("folder") else None
    old_files = list(meeting.get("files") or [])

    name = clean_name(meeting["name"])
    folder = unique_folder(output_dir if not old_folder else old_folder.parent, name, old_folder)
    name = folder.name
    if old_folder and old_folder.exists():
        _rename(old_folder, folder)
    folder.mkdir(parents=True, exist_ok=True)

    names = file_names(name)
    # Move each existing file to its new name rather than writing copies and deleting
    # "old" ones; on a case-insensitive file system those can be the same file.
    for f in old_files:
        kind = _kind(f)
        if kind and (folder / f).exists() and f != names[kind]:
            target = folder / names[kind]
            if target.exists() and not _same_name(f, names[kind]):
                target.unlink()
            _rename(folder / f, target)
    if wav_source and wav_source.exists():
        shutil.move(str(wav_source), folder / names["wav"])

    meeting = {**meeting, "name": name, "folder": str(folder)}
    files = [names["transcript"], names["srt"], names["summary"], names["json"]]
    if (folder / names["wav"]).exists():
        files.append(names["wav"])
    meeting["files"] = files

    write_atomic(folder / names["transcript"], render_txt(meeting))
    write_atomic(folder / names["srt"], render_srt(meeting))
    write_atomic(folder / names["summary"], render_summary_md(meeting))
    # The JSON is the source of truth, so it's written last.
    write_atomic(folder / names["json"], json.dumps({"app": APP_MARKER, **meeting}, indent=2, ensure_ascii=False))
    current = {f.casefold() for f in files}
    for f in old_files:
        if f.casefold() not in current and (folder / f).exists():
            (folder / f).unlink()
    return meeting


# What the system calls its restorable-delete folder, for UI text.
TRASH_NAME = "Recycle Bin" if os.name == "nt" else "Trash"


def to_recycle_bin(path: Path) -> None:
    """Move a folder to the Recycle Bin / Trash (restorable), never a hard delete."""
    if os.name == "nt":
        _windows_recycle(path)
    elif sys.platform == "darwin":
        _macos_trash(path)
    else:
        _freedesktop_trash(path)
    if path.exists():
        raise OSError(f"Couldn't move the folder to the {TRASH_NAME}. Is a file open?")


def _windows_recycle(path: Path) -> None:
    import ctypes
    from ctypes import wintypes

    class SHFILEOPSTRUCTW(ctypes.Structure):
        _fields_ = [
            ("hwnd", wintypes.HWND),
            ("wFunc", wintypes.UINT),
            ("pFrom", wintypes.LPCWSTR),
            ("pTo", wintypes.LPCWSTR),
            ("fFlags", ctypes.c_uint16),
            ("fAnyOperationsAborted", wintypes.BOOL),
            ("hNameMappings", ctypes.c_void_p),
            ("lpszProgressTitle", wintypes.LPCWSTR),
        ]

    fo_delete, fof_silent, fof_noconfirmation, fof_allowundo, fof_noerrorui = 3, 0x4, 0x10, 0x40, 0x400
    op = SHFILEOPSTRUCTW(
        None, fo_delete, str(path.resolve()) + "\0", None,  # pFrom must be double-null terminated
        fof_allowundo | fof_noconfirmation | fof_silent | fof_noerrorui, False, None, None,
    )
    rc = ctypes.windll.shell32.SHFileOperationW(ctypes.byref(op))
    if rc or op.fAnyOperationsAborted or path.exists():
        raise OSError(f"Windows couldn't move the folder to the Recycle Bin (code {rc}). Is a file open?")


def _macos_trash(path: Path) -> None:
    """Ask Finder, so "Put Back" works. The path is passed as an argument, never spliced into the script."""
    import subprocess

    script = 'on run argv\ntell application "Finder" to delete (POSIX file (item 1 of argv) as alias)\nend run'
    subprocess.run(["osascript", "-e", script, str(path.resolve())], check=True, capture_output=True, timeout=30)


def _freedesktop_trash(path: Path) -> None:
    """Linux: `gio trash` when available, else the freedesktop.org Trash spec in the home trash."""
    import shutil
    import subprocess
    from datetime import datetime
    from urllib.parse import quote

    if shutil.which("gio"):
        if subprocess.run(["gio", "trash", str(path)], capture_output=True, timeout=30).returncode == 0:
            return
    trash = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") / "Trash"
    (trash / "files").mkdir(parents=True, exist_ok=True)
    (trash / "info").mkdir(parents=True, exist_ok=True)
    name, n = path.name, 1
    while (trash / "files" / name).exists() or (trash / "info" / f"{name}.trashinfo").exists():
        n += 1
        name = f"{path.name}.{n}"
    info = f"[Trash Info]\nPath={quote(str(path.resolve()))}\nDeletionDate={datetime.now():%Y-%m-%dT%H:%M:%S}\n"
    (trash / "info" / f"{name}.trashinfo").write_text(info, encoding="utf-8")
    shutil.move(str(path), trash / "files" / name)


def open_in_file_manager(folder: Path) -> None:
    """Show a folder in Explorer, Finder or the Linux file manager."""
    if os.name == "nt":
        os.startfile(folder)  # noqa: S606 (local desktop app)
        return
    import subprocess

    subprocess.Popen(["open" if sys.platform == "darwin" else "xdg-open", str(folder)])  # noqa: S603


def read_meeting(path: Path) -> dict | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if not isinstance(data, dict) or data.get("app") != APP_MARKER or "id" not in data:
        return None
    data.pop("app", None)
    data["folder"] = str(path.parent)  # trust the real location if the user moved it
    return data


def candidate_files(output_dir: Path) -> list[list[Path]]:
    """For each meeting folder, the JSON files that might be its meeting file."""
    if not output_dir.exists():
        return []
    return [sorted(folder.glob("*.json")) for folder in output_dir.iterdir() if folder.is_dir()]
